package com.photoconnect.dto;

/**
 * Ephemeral checkout input. Card values are used only to select a deterministic
 * local demo outcome and are never persisted, logged, or sent externally.
 */
public class DemoPaymentRequest {
    private String paymentMethod;
    private String cardholderName;
    private String cardNumber;
    private String expiry;
    private String cvv;

    public String getPaymentMethod() {
        return paymentMethod;
    }

    public void setPaymentMethod(String paymentMethod) {
        this.paymentMethod = paymentMethod;
    }

    public String getCardholderName() {
        return cardholderName;
    }

    public void setCardholderName(String cardholderName) {
        this.cardholderName = cardholderName;
    }

    public String getCardNumber() {
        return cardNumber;
    }

    public void setCardNumber(String cardNumber) {
        this.cardNumber = cardNumber;
    }

    public String getExpiry() {
        return expiry;
    }

    public void setExpiry(String expiry) {
        this.expiry = expiry;
    }

    public String getCvv() {
        return cvv;
    }

    public void setCvv(String cvv) {
        this.cvv = cvv;
    }
}
